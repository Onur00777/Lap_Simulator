import {
  evaluateCorneringBalance,
  longitudinalCoefficients,
  peakSlip,
  wheelLoads,
  type PowertrainParams,
  type VehicleParams,
} from '../physics';
import type { TVControllerParams } from '../dynamics/yaw-controller';
import { banner, cArray1D, cf } from './c-format';
import type { TorqueMap } from './torque-map';
import { CODEGEN_VERSION } from './vcu-files';

export interface AutogenDynamicsTables {
  steerAxisDeg: number[];
  speedAxisKph: number[];
  /**Total torque request [Nm] (both rear motors combined): [pedalIdx][speedIdx] */
  totalTorqueNm: number[][];
  /**Differential torque Delta_T [Nm] (+ = RR gets +dT, RL gets -dT for left turn): [steerIdx][speedIdx] */
  tvDeltaTorqueNm: number[][];
  /**Longitudinal acceleration axis [m/s^2] for Launch/Traction Control slip target */
  axAxisMps2: number[];
  /**Optimal target slip ratio kappa* [-] vs ax_mps2 */
  tcSlipTarget: number[];
  /**Chassis understeer gradient [deg/G] at 15 m/s, 0.5 G */
  understeerDegPerG: number;
  /**Nominal accumulator power cap [kW] */
  nominalPowerCapKW: number;
}

export function buildAutogenDynamicsTables(
  veh: VehicleParams,
  pt: PowertrainParams,
  tm: TorqueMap,
  tv: TVControllerParams,
): AutogenDynamicsTables {
  const steerAxisDeg = [0, 2, 4, 6, 8, 10, 12, 15, 18, 22, 26];
  const speedAxisKph = tm.speedKph;

  // 1. Total torque request [Nm] across all driven motors
  const totalTorqueNm = tm.torque.map((row) => row.map((tPerMotor) => tPerMotor * pt.motorCount));

  // 2. Chassis understeer gradient at reference cornering state (15 m/s, 0.5 G)
  const usg = evaluateCorneringBalance(veh, 15, 0, 0.5 * 9.81);

  // 3. 2D Torque Vectoring Delta-Torque Matrix: Steer Angle [deg] x Speed [km/h] -> dT [Nm]
  const ayLimAt = (vx: number): number => {
    const tab = tv.ayLimitTable;
    if (!tab || tab.speed.length === 0) return tv.ayLimit;
    if (vx <= tab.speed[0]) return tab.ay[0];
    const last = tab.speed.length - 1;
    if (vx >= tab.speed[last]) return tab.ay[last];
    let i = 0;
    while (i < last - 1 && vx >= tab.speed[i + 1]) i++;
    const f = (vx - tab.speed[i]) / Math.max(1e-6, tab.speed[i + 1] - tab.speed[i]);
    return tab.ay[i] + f * (tab.ay[i + 1] - tab.ay[i]);
  };

  const kusChassisRadPerMps2 = (usg.understeerDegPerG * (Math.PI / 180)) / 9.81;
  const deltaKus = Math.max(0, kusChassisRadPerMps2 - tv.understeerTarget);

  const tvDeltaTorqueNm = steerAxisDeg.map((steerDeg) =>
    speedAxisKph.map((kph) => {
      const vx = kph / 3.6;
      if (vx < tv.minSpeed || Math.abs(steerDeg) < 1e-6) return 0;
      const steerRad = (steerDeg * Math.PI) / 180;
      const rTarget = Math.min(
        (0.95 * ayLimAt(vx)) / vx,
        (vx * steerRad) / Math.max(0.2, tv.wheelbase + tv.understeerTarget * vx * vx),
      );
      const rNatural = (vx * steerRad) / Math.max(0.2, tv.wheelbase + kusChassisRadPerMps2 * vx * vx);
      const yawErrFeedforward = rTarget - rNatural;
      const ayEst = vx * rTarget;
      // Feedforward yaw moment from desired understeer reduction + proportional yaw rate support
      const mzFeedforward = Math.min(
        tv.mzLimit,
        Math.max(-tv.mzLimit, tv.kp * yawErrFeedforward + veh.mass * ayEst * deltaKus * 18.0),
      );
      const dT = (mzFeedforward * tv.wheelRadius) / (tv.trackWidth * tv.gearRatio * tv.gearboxEfficiency);
      return Math.max(-tv.motorTorqueLimit, Math.min(tv.motorTorqueLimit, dT));
    }),
  );

  // 4. Launch Control / Traction Control target slip-ratio table vs longitudinal acceleration ax [m/s^2]
  const axAxisMps2 = [0, 2, 4, 6, 8, 10, 12, 14, 16];
  const tcSlipTarget = axAxisMps2.map((ax) => {
    const loads = wheelLoads(veh, 12, ax, 0);
    const fzRearWheel = Math.max(120, 0.5 * (loads.rl + loads.rr));
    const kappaPeak = peakSlip(longitudinalCoefficients(veh.tire, fzRearWheel));
    return Number((0.92 * kappaPeak).toFixed(5));
  });

  return {
    steerAxisDeg,
    speedAxisKph,
    totalTorqueNm,
    tvDeltaTorqueNm,
    axAxisMps2,
    tcSlipTarget,
    understeerDegPerG: usg.understeerDegPerG,
    nominalPowerCapKW: pt.batteryPowerLimit / 1000,
  };
}

