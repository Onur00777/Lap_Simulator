import { defaultTVParams } from '../dynamics/yaw-controller';
import type { PowertrainParams } from '../physics/powertrain';
import type { VehicleParams } from '../physics/vehicle';
import { cf } from './c-format';
import type { GeneratedFile } from './vcu-files';

/** Generate the hardware-independent dynamics and torque authorization task. */
export function generateVcuDynamics(veh: VehicleParams, pt: PowertrainParams): [GeneratedFile, GeneratedFile] {
  if (pt.motorCount !== 1 && pt.motorCount !== 2) throw new RangeError('VCU generation requires one or two motors.');
  const tv = defaultTVParams(veh, pt);
  const trackWidth = veh.trackWidthRear ?? veh.trackWidth;
  const positive = [tv.wheelbase, trackWidth, tv.wheelRadius, tv.gearRatio, tv.gearboxEfficiency, tv.motorTorqueLimit];
  if (positive.some((value) => !Number.isFinite(value) || value <= 0)) throw new RangeError('VCU geometry, gearing and torque limits must be finite and positive.');
  const deltaNmPerMz = tv.wheelRadius / (trackWidth * tv.gearRatio * tv.gearboxEfficiency);
  const header = `/* Generated by ApexLapSim. Hardware-independent application task. */
#ifndef APEX_VCU_DYNAMICS_H
#define APEX_VCU_DYNAMICS_H

#include <stdbool.h>
#include <stdint.h>

#define APEX_VCU_MOTOR_COUNT (${pt.motorCount}U)
#define APEX_VCU_TASK_PERIOD_MS (10U)
#define APEX_VCU_WATCHDOG_MS (50U)
#define APEX_VCU_CAN_TIMEOUT_MS (100U)
#define APEX_VCU_FAULT_INTERLOCK (0x01U)
#define APEX_VCU_FAULT_APPS (0x02U)
#define APEX_VCU_FAULT_INVERTER (0x04U)
#define APEX_VCU_FAULT_WATCHDOG (0x08U)
#define APEX_VCU_FAULT_INPUT (0x10U)
#define APEX_VCU_FAULT_BRAKE_APPS (0x20U)

typedef enum
{
    APEX_VCU_INIT = 0,
    APEX_VCU_PRECHARGE_OK,
    APEX_VCU_RUN_TORQUE_ENABLED,
    APEX_VCU_SAFE_TORQUE_OFF_FAULT
} ApexVcuMode;

typedef struct
{
    uint32_t now_ms;
    uint32_t inverter_last_rx_ms[APEX_VCU_MOTOR_COUNT];
    bool inverter_seen[APEX_VCU_MOTOR_COUNT];
    bool inverter_fault;
    bool hv_interlock_closed;
    bool precharge_complete;
    bool enable_request;
    bool reset_requested;
    bool brake_active;
    uint16_t apps1_permille;
    uint16_t apps2_permille;
    float vehicle_speed_mps;
    float road_steer_rad;
    float yaw_rate_rad_s;
    float torque_ceiling_nm; /* Per motor, from the hardware/BMS authority. */
} ApexVcuInputs;

typedef struct
{
    ApexVcuMode mode;
    uint32_t faults;
    uint32_t last_step_ms;
    float base_nm;
    float delta_nm;
    float yaw_integral_nm;
    float previous_torque_nm[APEX_VCU_MOTOR_COUNT];
    bool enable_armed;
} ApexVcuState;

typedef struct
{
    ApexVcuMode mode;
    uint32_t faults;
    bool inverter_enable;
    bool watchdog_service_permitted;
    float torque_nm[APEX_VCU_MOTOR_COUNT]; /* Single motor, or RL then RR. */
} ApexVcuOutputs;

void ApexVcu_Init(ApexVcuState *state, uint32_t now_ms);
ApexVcuOutputs ApexVcu_Step(ApexVcuState *state, const ApexVcuInputs *input);

#endif /* APEX_VCU_DYNAMICS_H */
`;

  const yaw = pt.motorCount === 2 ? `
    if ((input->vehicle_speed_mps >= ${cf(tv.minSpeed)}) && (state->base_nm > 0.0f))
    {
        const float v = input->vehicle_speed_mps;
        const float yaw_limit = ${cf(0.95 * tv.ayLimit)} / v;
        const float yaw_ref = ApexVcu_Clamp((v * input->road_steer_rad) / ${cf(tv.wheelbase)}, -yaw_limit, yaw_limit);
        const float error = yaw_ref - input->yaw_rate_rad_s;
        const float available = ApexVcu_Min(state->base_nm, ceiling - state->base_nm);
        const float candidate = state->yaw_integral_nm + (${cf(tv.ki * deltaNmPerMz)} * error * dt);
        const float unsaturated = (${cf(tv.kp * deltaNmPerMz)} * error) + candidate;
        const float target = ApexVcu_Clamp(unsaturated, -available, available);
        if (((unsaturated <= available) && (unsaturated >= -available)) ||
            ((unsaturated > available) && (error < 0.0f)) || ((unsaturated < -available) && (error > 0.0f)))
        {
            state->yaw_integral_nm = ApexVcu_Clamp(candidate, -available, available);
        }
        state->delta_nm = ApexVcu_Clamp(ApexVcu_Slew(state->delta_nm, target, 0.5f * slew), -available, available);
    }
    else
    {
        state->delta_nm = 0.0f;
        state->yaw_integral_nm = 0.0f;
    }
    output.torque_nm[0] = state->base_nm - state->delta_nm;
    output.torque_nm[1] = state->base_nm + state->delta_nm;
` : '    output.torque_nm[0] = state->base_nm;\n';

  const source = `/* Generated by ApexLapSim.\n * Integrator supplies validated inputs, independent hardware watchdog and the shutdown path.\n * Review timing, limits and required MISRA-C:2012 analyses for the target ECU.\n */
#include "vcu_dynamics.h"

#define APEX_VCU_TORQUE_LIMIT_NM (${cf(tv.motorTorqueLimit)})
#define APEX_VCU_APPS_DELTA (100U)
#define APEX_VCU_APPS_IDLE (50U)
#define APEX_VCU_APPS_BRAKE (250U)
#define APEX_VCU_SLEW_NM_PER_S (${cf(tv.motorTorqueLimit * 4)})

static float ApexVcu_Min(float a, float b)
{
    float result = a;
    if (b < a) { result = b; }
    return result;
}

static float ApexVcu_Clamp(float value, float low, float high)
{
    float result = value;
    if (value < low) { result = low; }
    else if (value > high) { result = high; }
    else { /* In range. */ }
    return result;
}

static float ApexVcu_Slew(float old, float target, float limit)
{
    return old + ApexVcu_Clamp(target - old, -limit, limit);
}

static void ApexVcu_ClearTorque(ApexVcuState *state)
{
    uint32_t i;
    state->base_nm = 0.0f;
    state->delta_nm = 0.0f;
    state->yaw_integral_nm = 0.0f;
    for (i = 0U; i < APEX_VCU_MOTOR_COUNT; i++)
    {
        state->previous_torque_nm[i] = 0.0f;
    }
}

void ApexVcu_Init(ApexVcuState *state, uint32_t now_ms)
{
    state->mode = APEX_VCU_INIT;
    state->faults = 0U;
    state->last_step_ms = now_ms;
    state->enable_armed = false;
    ApexVcu_ClearTorque(state);
}

ApexVcuOutputs ApexVcu_Step(ApexVcuState *state, const ApexVcuInputs *input)
{
    ApexVcuOutputs output = {APEX_VCU_INIT, 0U, false, false, {0.0f}};
    const uint32_t elapsed = input->now_ms - state->last_step_ms;
    const uint32_t apps1 = (uint32_t)input->apps1_permille;
    const uint32_t apps2 = (uint32_t)input->apps2_permille;
    const uint32_t pedal = (apps1 < apps2) ? apps1 : apps2;
    const uint32_t difference = (apps1 >= apps2) ? (apps1 - apps2) : (apps2 - apps1);
    const bool apps_ok = (apps1 <= 1000U) && (apps2 <= 1000U) && (difference <= APEX_VCU_APPS_DELTA);
    const bool pedal_idle = (apps1 <= APEX_VCU_APPS_IDLE) && (apps2 <= APEX_VCU_APPS_IDLE);
    const bool interlock_ok = input->precharge_complete && input->hv_interlock_closed;
    const bool signals_ok = (input->vehicle_speed_mps >= 0.0f) && (input->vehicle_speed_mps <= 160.0f) &&
        (input->road_steer_rad >= -1.2f) && (input->road_steer_rad <= 1.2f) &&
        (input->yaw_rate_rad_s >= -20.0f) && (input->yaw_rate_rad_s <= 20.0f) &&
        (input->torque_ceiling_nm >= 0.0f) && (input->torque_ceiling_nm <= 3276.7f);
    bool heartbeat_ok = !input->inverter_fault;
    uint32_t i;
    state->last_step_ms = input->now_ms;
    for (i = 0U; i < APEX_VCU_MOTOR_COUNT; i++)
    {
        if ((!input->inverter_seen[i]) || ((input->now_ms - input->inverter_last_rx_ms[i]) >= APEX_VCU_CAN_TIMEOUT_MS))
        {
            heartbeat_ok = false;
        }
    }

    if (elapsed >= APEX_VCU_WATCHDOG_MS) { state->faults |= APEX_VCU_FAULT_WATCHDOG; }
    if (!apps_ok) { state->faults |= APEX_VCU_FAULT_APPS; }
    if (!signals_ok) { state->faults |= APEX_VCU_FAULT_INPUT; }
    if (input->brake_active && (pedal > APEX_VCU_APPS_BRAKE)) { state->faults |= APEX_VCU_FAULT_BRAKE_APPS; }
    if (state->mode == APEX_VCU_RUN_TORQUE_ENABLED)
    {
        if (!interlock_ok) { state->faults |= APEX_VCU_FAULT_INTERLOCK; }
        if (!heartbeat_ok) { state->faults |= APEX_VCU_FAULT_INVERTER; }
    }

    if (state->faults != 0U) { state->mode = APEX_VCU_SAFE_TORQUE_OFF_FAULT; }
    switch (state->mode)
    {
        case APEX_VCU_INIT:
            if (interlock_ok && heartbeat_ok && pedal_idle)
            {
                state->mode = APEX_VCU_PRECHARGE_OK;
                state->enable_armed = !input->enable_request;
            }
            break;
        case APEX_VCU_PRECHARGE_OK:
            if ((!interlock_ok) || (!heartbeat_ok)) { ApexVcu_Init(state, input->now_ms); }
            else if (!input->enable_request) { state->enable_armed = true; }
            else if (state->enable_armed)
            {
                state->enable_armed = false;
                if (pedal_idle) { state->mode = APEX_VCU_RUN_TORQUE_ENABLED; }
            }
            else { /* Await a new enable request. */ }
            break;
        case APEX_VCU_RUN_TORQUE_ENABLED:
            if (!input->enable_request) { ApexVcu_Init(state, input->now_ms); }
            break;
        case APEX_VCU_SAFE_TORQUE_OFF_FAULT:
            if (input->reset_requested && (!input->precharge_complete) && (!input->enable_request) &&
                pedal_idle && apps_ok && signals_ok && (!input->inverter_fault) && (elapsed < APEX_VCU_WATCHDOG_MS))
            {
                ApexVcu_Init(state, input->now_ms);
            }
            break;
        default:
            state->faults |= APEX_VCU_FAULT_INPUT;
            state->mode = APEX_VCU_SAFE_TORQUE_OFF_FAULT;
            break;
    }

    output.mode = state->mode;
    output.faults = state->faults;
    output.watchdog_service_permitted = state->faults == 0U;
    output.inverter_enable = state->mode == APEX_VCU_RUN_TORQUE_ENABLED;
    if ((!output.inverter_enable) || input->brake_active || pedal_idle)
    {
        ApexVcu_ClearTorque(state);
    }
    else
    {
        const float ceiling = ApexVcu_Min(APEX_VCU_TORQUE_LIMIT_NM, input->torque_ceiling_nm);
        const float demand = ceiling * ((float)pedal / 1000.0f);
        const float dt = (float)elapsed / 1000.0f;
        const float slew = APEX_VCU_SLEW_NM_PER_S * dt;
        /* Each wheel's upward slew is bounded by the sum of the two half-rate increments. */
        state->base_nm = ApexVcu_Min(demand, ApexVcu_Slew(state->base_nm, demand, ${pt.motorCount === 2 ? '0.5f * slew' : 'slew'}));
${yaw.trimEnd()}
        for (i = 0U; i < APEX_VCU_MOTOR_COUNT; i++)
        {
            output.torque_nm[i] = ApexVcu_Clamp(output.torque_nm[i], 0.0f,
                ApexVcu_Min(ceiling, state->previous_torque_nm[i] + slew));
            state->previous_torque_nm[i] = output.torque_nm[i];
        }
    }
    return output;
}
`;
  return [
    { name: 'vcu_dynamics.h', language: 'c', content: header },
    { name: 'vcu_dynamics.c', language: 'c', content: source },
  ];
}
