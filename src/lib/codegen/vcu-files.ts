export function generateTorqueVectoringSource(p: TVControllerParams, veh: VehicleParams, pt: PowertrainParams): string {
  const tab = p.ayLimitTable ?? { speed: [0, 100], ay: [p.ayLimit, p.ayLimit] };
  const n = tab.speed.length;
  return `${header('vcu_torque_vectoring.c', 'Yaw-rate feedback PI direct yaw moment controller (STM32 / FreeRTOS ready)', veh, pt, [
    '',
    'Reference yaw rate : r_ref = vx * delta / (L + K_us * vx^2), |r_ref| <= 0.95 * ay_lim(vx) / vx',
    'Feedback           : Mz = Kp * e + Ki * integral(e), conditional-integration anti-windup',
    'Allocation         : dT = Mz * r_w / (t * G * eta);  T_RR = T_req/2 + dT,  T_RL = T_req/2 - dT',
    'ay_lim(vx)         : steady-state lateral limit of the TV two-track model (simulated)',
    '',
    'Build: compile with -DVCU_TV_USE_FREERTOS to include the periodic FreeRTOS task wrapper.',
  ])}

#include <stddef.h>
#include "vcu_torque_vectoring.h"

#if defined(VCU_TV_USE_FREERTOS)
#include "FreeRTOS.h"
#include "task.h"
#endif

#define VCU_TV_AY_POINTS (${n}U)

/* Lateral acceleration limit schedule [m/s^2] versus speed [m/s] from the simulation envelope. */
static const float32_t VCU_TV_AyAxis_mps[VCU_TV_AY_POINTS] = {${cArray1D(tab.speed, 2, 8)} };
static const float32_t VCU_TV_AyLimit_mps2[VCU_TV_AY_POINTS] = {${cArray1D(tab.ay, 4, 9)} };

const VCU_TV_Params_t VCU_TV_DefaultParams =
{
    ${cf(p.wheelbase)},   /* wheelbase_m */
    ${cf(p.trackWidth)},   /* track_width_m */
    ${cf(p.wheelRadius)},   /* wheel_radius_m */
    ${cf(p.gearRatio)},   /* gear_ratio */
    ${cf(p.gearboxEfficiency)},   /* gearbox_efficiency */
    ${cf(p.understeerTarget)},   /* understeer_target_rad_per_mps2 */
    ${cf(p.kp)},   /* kp_Nm_per_radps */
    ${cf(p.ki)},   /* ki_Nm_per_rad */
    ${cf(p.mzLimit)},   /* mz_limit_Nm */
    ${cf(p.motorTorqueLimit)},   /* motor_torque_limit_Nm */
    ${cf(p.minSpeed)},   /* min_speed_mps */
    ${cf(p.dt)}    /* dt_s */
};

static float32_t VCU_TV_Clamp(float32_t x, float32_t lo, float32_t hi)
{
    float32_t y = x;
    if (y < lo)
    {
        y = lo;
    }
    else if (y > hi)
    {
        y = hi;
    }
    else
    {
        /* within limits: no action */
    }
    return y;
}

static int32_t VCU_TV_Sign(float32_t x)
{
    int32_t s = 0;
    if (x > 0.0f)
    {
        s = 1;
    }
    else if (x < 0.0f)
    {
        s = -1;
    }
    else
    {
        /* zero */
    }
    return s;
}

static float32_t VCU_TV_Abs(float32_t x)
{
    float32_t y = x;
    if (y < 0.0f)
    {
        y = -y;
    }
    return y;
}

void VCU_TV_Init(VCU_TV_State_t *state)
{
    if (state != NULL)
    {
        state->integrator_Nm = 0.0f;
    }
}

float32_t VCU_TV_AyLimit(float32_t vx_mps)
{
    float32_t ay;
    if (vx_mps <= VCU_TV_AyAxis_mps[0U])
    {
        ay = VCU_TV_AyLimit_mps2[0U];
    }
    else if (vx_mps >= VCU_TV_AyAxis_mps[VCU_TV_AY_POINTS - 1U])
    {
        ay = VCU_TV_AyLimit_mps2[VCU_TV_AY_POINTS - 1U];
    }
    else
    {
        uint32_t i = 0U;
        float32_t f;
        while ((i < (VCU_TV_AY_POINTS - 2U)) && (vx_mps >= VCU_TV_AyAxis_mps[i + 1U]))
        {
            i++;
        }
        f = (vx_mps - VCU_TV_AyAxis_mps[i]) / (VCU_TV_AyAxis_mps[i + 1U] - VCU_TV_AyAxis_mps[i]);
        ay = VCU_TV_AyLimit_mps2[i] + (f * (VCU_TV_AyLimit_mps2[i + 1U] - VCU_TV_AyLimit_mps2[i]));
    }
    return ay;
}

float32_t VCU_TV_YawRateTarget(const VCU_TV_Params_t *params, float32_t vx_mps, float32_t steer_rad)
{
    float32_t r_ref = 0.0f;
    if (params != NULL)
    {
        const float32_t v = (vx_mps > 0.1f) ? vx_mps : 0.1f;
        const float32_t r_lin = (v * steer_rad) /
                                (params->wheelbase_m + (params->understeer_target_rad_per_mps2 * v * v));
        const float32_t r_max = (0.95f * VCU_TV_AyLimit(v)) / v;
        r_ref = VCU_TV_Clamp(r_lin, -r_max, r_max);
    }
    return r_ref;
}

void VCU_TV_Step(const VCU_TV_Params_t *params, VCU_TV_State_t *state,
                 const VCU_TV_Inputs_t *inputs, VCU_TV_Outputs_t *outputs)
{
    if ((params != NULL) && (state != NULL) && (inputs != NULL) && (outputs != NULL))
    {
        const float32_t base = 0.5f * inputs->torque_request_Nm;
        const float32_t t_lim = params->motor_torque_limit_Nm;
        if (inputs->vx_mps < params->min_speed_mps)
        {
            const float32_t t_eq = VCU_TV_Clamp(base, -t_lim, t_lim);
            state->integrator_Nm = 0.0f;
            outputs->torque_rl_Nm = t_eq;
            outputs->torque_rr_Nm = t_eq;
            outputs->mz_Nm = 0.0f;
            outputs->yaw_rate_ref_rps = 0.0f;
            outputs->yaw_rate_err_rps = 0.0f;
            outputs->saturated = false;
        }
        else
        {
            const float32_t mz_lim = params->mz_limit_Nm;
            const float32_t r_ref = VCU_TV_YawRateTarget(params, inputs->vx_mps, inputs->steer_rad);
            const float32_t err = r_ref - inputs->yaw_rate_rps;
            const float32_t integ_candidate = state->integrator_Nm + (params->ki_Nm_per_rad * err * params->dt_s);
            const float32_t mz_unsat = (params->kp_Nm_per_radps * err) + integ_candidate;
            const float32_t mz = VCU_TV_Clamp(mz_unsat, -mz_lim, mz_lim);
            const bool sat_mz = (mz_unsat > mz_lim) || (mz_unsat < -mz_lim);
            float32_t d_t;
            float32_t rr_raw;
            float32_t rl_raw;
            bool sat_motor;

            /* conditional integration: freeze the integrator while it would deepen saturation */
            if ((!sat_mz) || (VCU_TV_Sign(err) != VCU_TV_Sign(mz_unsat)))
            {
                state->integrator_Nm = VCU_TV_Clamp(integ_candidate, -mz_lim, mz_lim);
            }

            d_t = (mz * params->wheel_radius_m) /
                  (params->track_width_m * params->gear_ratio * params->gearbox_efficiency);
            rr_raw = base + d_t;
            rl_raw = base - d_t;
            sat_motor = (VCU_TV_Abs(rr_raw) > t_lim) || (VCU_TV_Abs(rl_raw) > t_lim);

            outputs->torque_rr_Nm = VCU_TV_Clamp(rr_raw, -t_lim, t_lim);
            outputs->torque_rl_Nm = VCU_TV_Clamp(rl_raw, -t_lim, t_lim);
            outputs->mz_Nm = mz;
            outputs->yaw_rate_ref_rps = r_ref;
            outputs->yaw_rate_err_rps = err;
            outputs->saturated = sat_mz || sat_motor;
        }
    }
}

#if defined(VCU_TV_USE_FREERTOS)
/**
 * @brief  Periodic FreeRTOS task (create with xTaskCreate at high priority, ${Math.round(p.dt * 1000)} ms period).
 * @note   MISRA deviation (Rule 2.1 / Dir 4.x): intentional infinite task loop.
 */
void VCU_TV_Task(void *argument)
{
    VCU_TV_State_t state;
    VCU_TV_Inputs_t inputs;
    VCU_TV_Outputs_t outputs;
    TickType_t last_wake = xTaskGetTickCount();
    const TickType_t period = pdMS_TO_TICKS(VCU_TV_TASK_PERIOD_MS);

    (void)argument;
    VCU_TV_Init(&state);

    for (;;)
    {
        vTaskDelayUntil(&last_wake, period);
        VCU_HAL_ReadTvInputs(&inputs);
        VCU_TV_Step(&VCU_TV_DefaultParams, &state, &inputs, &outputs);
        VCU_HAL_WriteMotorTorques(outputs.torque_rl_Nm, outputs.torque_rr_Nm);
    }
}
#endif
`;
}

/** Firmware TV calibration derived from the simulated TV envelope. */
export function buildFirmwareTvParams(veh: VehicleParams, pt: PowertrainParams, overrides: Partial<TVControllerParams> = {}): TVControllerParams {
  const vTop = speedFromMotorRpm(veh, pt.motorMaxRpm, pt.gearRatio);
  const env = buildTwoTrackEnvelope(veh, pt, vTop + 2, 'tv', 1);
  const speed: number[] = [];
  const ay: number[] = [];
  for (let v = 0; v <= Math.ceil(vTop / 5) * 5; v += 5) {
    const i = Math.min(env.ayMax.length - 1, Math.round(v / env.dv));
    speed.push(v);
    ay.push(steadyStateLateralLimit(veh, env.ayMax[i], v));
  }
  const base = defaultTVParams(veh, pt, ay[Math.min(3, ay.length - 1)]);
  return { ...base, ayLimitTable: { speed, ay }, ...overrides };
}

export interface VcuBundle {
  files: GeneratedFile[];
  torqueMap: TorqueMap;
  tvParams: TVControllerParams;
}

/** Appended when the calibration is exported for a TOSFED Körfez layout. */
function korfezPresetBlock(trackId: string, pt: PowertrainParams, tv: TVControllerParams): string {
  return [
    '',
    '/* TOSFED Körfez — layout this torque / regen / yaw calibration was solved for. */',
    `#define KORFEZ_TRACK_PRESET            "${trackId}"`,
    `#define KORFEZ_REGEN_LIMIT_W           (${Math.round(pt.regenPowerLimit)}U)`,
    `#define KORFEZ_TV_KP_NM_PER_RADPS      (${cf(tv.kp)})`,
    `#define KORFEZ_TV_KI_NM_PER_RAD        (${cf(tv.ki)})`,
    '#define KORFEZ_TIMING_RESOLUTION_S     (0.001f)',
    '',
  ].join('\n');
}

export function generateVcuBundle(
  veh: VehicleParams,
  pt: PowertrainParams,
  opts: { map?: EfficiencyMap; torqueMap?: TorqueMapOptions; tv?: Partial<TVControllerParams>; korfezTrackId?: string } = {},
): VcuBundle {
  const map = opts.map ?? buildEfficiencyMap(pt);
  const torqueMap = buildTorqueMap(veh, pt, map, opts.torqueMap);
  const tvParams = buildFirmwareTvParams(veh, pt, opts.tv);
  const files: GeneratedFile[] = [
    { name: 'vcu_torque_map.h', language: 'c', content: generateTorqueMapHeader(torqueMap, veh, pt) },
    { name: 'vcu_torque_vectoring.h', language: 'c', content: generateTorqueVectoringHeader(tvParams, veh, pt) },
    { name: 'vcu_torque_vectoring.c', language: 'c', content: generateTorqueVectoringSource(tvParams, veh, pt) },
  ];
  if (opts.korfezTrackId) {
    const block = korfezPresetBlock(opts.korfezTrackId, pt, tvParams);
    files[0].content = files[0].content.replace('#endif /* VCU_TORQUE_MAP_H */', `${block}#endif /* VCU_TORQUE_MAP_H */`);
    files[2].content = files[2].content.replace('#include "vcu_torque_vectoring.h"', `#include "vcu_torque_vectoring.h"\n#include "vcu_torque_map.h" /* KORFEZ_TRACK_PRESET */`);
  }
  return { torqueMap, tvParams, files };
}
