export function generateTorqueMapHeader(tm: TorqueMap, veh: VehicleParams, pt: PowertrainParams): string {
  const nP = tm.pedalPct.length;
  const nS = tm.speedKph.length;
  const rows = tm.torque
    .map((row, i) => `    /* ${String(tm.pedalPct[i]).padStart(3, ' ')} % */ {${cArray1D(row, 3, 9)} }`)
    .join(',\n');
  const limitRow = tm.limitedBy.map((l) => l[0].toUpperCase()).join(' ');
  return `${header('vcu_torque_map.h', 'Driver torque request map: pedal travel [%] x speed [km/h] -> motor torque [Nm]', veh, pt, [
    '',
    `Pedal progression : T = T_avail(v) * (pedal/100)^${tm.pedalGamma}`,
    `Traction limit    : Pacejka Fx at TC slip set point kappa* = ${tm.slipTarget.toFixed(4)}`,
    `Lift-off regen    : ${tm.coastRegenTorque} Nm per motor at 0 % pedal`,
    `Column limiter    : ${limitRow}  (T=traction, M=motor, B=battery, R=max rpm)`,
    '',
    'Include this header in exactly one translation unit (the VCU torque-request task).',
  ])}

#ifndef VCU_TORQUE_MAP_H
#define VCU_TORQUE_MAP_H

#include <stdint.h>

#ifndef VCU_FLOAT32_T_DEFINED
#define VCU_FLOAT32_T_DEFINED
typedef float float32_t;
#endif

#define VCU_TM_PEDAL_POINTS          (${nP}U)
#define VCU_TM_SPEED_POINTS          (${nS}U)
#define VCU_TM_MOTOR_TORQUE_MAX_NM   (${cf(pt.motorPeakTorque)})
#define VCU_TM_TC_SLIP_TARGET        (${cf(tm.slipTarget, 5)})
#define VCU_TM_MAX_SPEED_KPH         (${cf(tm.maxSpeedKph, 5)})

/* Breakpoints: accelerator pedal travel [%] */
static const float32_t VCU_TM_PedalAxis_pct[VCU_TM_PEDAL_POINTS] = {${cArray1D(tm.pedalPct, 1, 7)} };

/* Breakpoints: vehicle speed [km/h] */
static const float32_t VCU_TM_SpeedAxis_kph[VCU_TM_SPEED_POINTS] = {${cArray1D(tm.speedKph, 1, 7)} };

/* Motor torque request [Nm per motor]; rows = pedal, columns = speed. Negative = regenerative. */
static const float32_t VCU_TM_Torque_Nm[VCU_TM_PEDAL_POINTS][VCU_TM_SPEED_POINTS] = {
${rows}
};

/* Available torque at 100 % pedal [Nm per motor] (diagnostics / torque-limit telemetry). */
static const float32_t VCU_TM_AvailableTorque_Nm[VCU_TM_SPEED_POINTS] = {${cArray1D(tm.availableTorque, 3, 9)} };

/**
 * @brief  Clamp a query to the axis range. NaN inputs map to the lower breakpoint.
 */
static inline float32_t VCU_TM_ClampAxis(const float32_t axis[], uint32_t n, float32_t x)
{
    float32_t y = x;
    if (!(y >= axis[0U]))
    {
        y = axis[0U];
    }
    else if (y > axis[n - 1U])
    {
        y = axis[n - 1U];
    }
    else
    {
        /* inside the table range: no action */
    }
    return y;
}

/**
 * @brief  Lower bracket index i with axis[i] <= x < axis[i + 1], limited to [0, n - 2].
 */
static inline uint32_t VCU_TM_FindIndex(const float32_t axis[], uint32_t n, float32_t x)
{
    uint32_t i = 0U;
    while ((i < (n - 2U)) && (x >= axis[i + 1U]))
    {
        i++;
    }
    return i;
}

/**
 * @brief  Bilinear interpolation of the driver torque map.
 * @param  pedal_pct  accelerator pedal travel [0 .. 100 %], clamped
 * @param  speed_kph  vehicle speed [km/h], clamped
 * @return motor torque request [Nm per motor]
 */
static inline float32_t VCU_TM_Interpolate(float32_t pedal_pct, float32_t speed_kph)
{
    const float32_t p = VCU_TM_ClampAxis(VCU_TM_PedalAxis_pct, VCU_TM_PEDAL_POINTS, pedal_pct);
    const float32_t s = VCU_TM_ClampAxis(VCU_TM_SpeedAxis_kph, VCU_TM_SPEED_POINTS, speed_kph);
    const uint32_t i = VCU_TM_FindIndex(VCU_TM_PedalAxis_pct, VCU_TM_PEDAL_POINTS, p);
    const uint32_t j = VCU_TM_FindIndex(VCU_TM_SpeedAxis_kph, VCU_TM_SPEED_POINTS, s);
    const float32_t tp = (p - VCU_TM_PedalAxis_pct[i]) / (VCU_TM_PedalAxis_pct[i + 1U] - VCU_TM_PedalAxis_pct[i]);
    const float32_t ts = (s - VCU_TM_SpeedAxis_kph[j]) / (VCU_TM_SpeedAxis_kph[j + 1U] - VCU_TM_SpeedAxis_kph[j]);
    const float32_t q00 = VCU_TM_Torque_Nm[i][j];
    const float32_t q01 = VCU_TM_Torque_Nm[i][j + 1U];
    const float32_t q10 = VCU_TM_Torque_Nm[i + 1U][j];
    const float32_t q11 = VCU_TM_Torque_Nm[i + 1U][j + 1U];
    const float32_t r0 = q00 + ((q01 - q00) * ts);
    const float32_t r1 = q10 + ((q11 - q10) * ts);
    return r0 + ((r1 - r0) * tp);
}

#endif /* VCU_TORQUE_MAP_H */
`;
}

